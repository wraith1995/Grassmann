"""The subspace relation ``⊑``, which decides where a value may be projected or embedded.

A vector may be projected onto a space (:class:`~grassmann.core.term.Project`) or embedded
into one (:class:`~grassmann.core.term.Embed`) exactly when the two spaces stand in this
relation. It is generated by two families of containment and closed under
reflexivity and transitivity::

    a summand of a direct sum
        s ⊑ ⊕(…, s, …)

    a fundamental subspace inside its map's endpoint
        Ker f  ⊑ dom f        CoImg f ⊑ dom f
        Img f  ⊑ cod f        CoKer f ⊑ cod f

                    dom f                       cod f
                  ┌───────┐                   ┌───────┐
                  │ Ker f │                   │ Img f │
                  │ CoImg │ ── f ──────────▶  │ CoKer │
                  └───────┘                   └───────┘

The decision is structural. Spaces are compared up to the one spelling difference that
carries no meaning — a static ``⊕ⁿ s`` against the explicit ``⊕(s,…,s)``, and a product
against itself with ⊗-units dropped — and a subspace node's ambient comes from its
declared endpoint when it has one, otherwise from synthesizing the defining map's space.
No coordinates are involved: realizing a containment as an actual inclusion of frames is
lowering's job, through :class:`~grassmann.core.basis.CompleteBasis`.
"""

from __future__ import annotations

from typing import Literal, TypeGuard, assert_never

from grassmann.core.space import (
    App,
    CoImg,
    CoKer,
    DimLit,
    Dual,
    Img,
    Ker,
    OPlus,
    OPlusRep,
    OProd,
    Scalar,
    Space,
    SpaceMeta,
    SVar,
    WithInner,
)


def _norm(s: Space) -> Space:
    """Canonicalize a space so two spellings of one space compare equal.

    A static ``⊕ⁿ s`` expands to the explicit ``⊕(s,…,s)``, so ``ℝⁿ`` matches however it was
    written, and a product drops its ⊗-units and collapses to its single remaining factor.
    Both rewrites are recursive.
    """
    match s:
        case OPlusRep(count, inner) if isinstance(count, DimLit):
            return OPlus(tuple([_norm(inner)] * count.value))
        case OPlus(spaces):
            return OPlus(tuple(_norm(x) for x in spaces))
        case OProd(spaces):
            # Drop the ⊗-unit and collapse a single-factor product to its factor: ``X ⊗ ℝ ≅ X``
            # and ``OProd((X,)) ≅ X``. That is what lets a degree-1 exterior power
            # ``Λ¹(V) = Img(alt)``, whose codomain is the 1-tuple ``V⊗¹ = OProd((V,))``, be
            # recognized as a subspace of ``V``.
            ns = [_norm(x) for x in spaces if not isinstance(x, Scalar)]
            if not ns:
                return Scalar()
            return ns[0] if len(ns) == 1 else OProd(tuple(ns))
        case Dual(inner):
            return Dual(_norm(inner))
        case _:  # audit: ok EX-WILDCARD — bail-default (§0): canonicalize specific else passthrough [approved 2026-07-03]
            return s


def _eq(a: Space, b: Space) -> bool:
    # Compare up to the canonical form, since the ℝⁿ ground can be written either as an
    # ``OPlusRep`` or as an explicit ``OPlus``.
    return a == b or _norm(a) == _norm(b)


def is_subspace(sub: Space, amb: Space) -> bool:
    """Decide ``sub ⊑ amb``: equality, a ⊕-summand, or a fundamental subspace of a map.

    The relation is reflexive and transitive, so the search descends through the summands
    of a direct sum and follows a fundamental subspace up to its map's domain or codomain
    before asking again.
    """
    if _eq(sub, amb):
        return True

    # FFS ⊑ ambient.
    if isinstance(amb, OPlus):
        # A summand (recursively/transitively) is a subspace.
        for comp in amb.spaces:
            if is_subspace(sub, comp):
                return True

    # FFS of a map sits inside its dom/cod.
    if isinstance(sub, (Ker, CoImg)):
        dom = _ffs_dom(sub)
        if dom is not None and is_subspace_or_eq(dom, amb):
            return True
    if isinstance(sub, (Img, CoKer)):  # audit: ok EX-ISINSTANCE-LADDER — safe direction: False only blocks project/embed [approved 2026-07-03]
        cod = _ffs_cod(sub)
        if cod is not None and is_subspace_or_eq(cod, amb):
            return True

    return False


def is_subspace_or_eq(a: Space, b: Space) -> bool:
    """Report whether ``a`` is a subspace of ``b`` or equal to it."""
    return _eq(a, b) or is_subspace(a, b)


def _ffs_dom(node: Ker | CoImg) -> Space | None:
    if node.source is not None:
        return node.source
    from .synth import InferError, map_domain_codomain

    try:
        dom, _ = map_domain_codomain(node.f)
        return dom
    except InferError:
        return None


def _ffs_cod(node: Img | CoKer) -> Space | None:
    if node.target is not None:
        return node.target
    from .synth import InferError, map_domain_codomain

    try:
        _, cod = map_domain_codomain(node.f)
        return cod
    except InferError:
        return None


# ---------------------------------------------------------------------------
# Canonical FFS / map-space probes.
# ---------------------------------------------------------------------------

FfsKind = Literal["img", "ker", "coimg", "coker"]


def is_ffs(s: Space) -> TypeGuard[Img | Ker | CoImg | CoKer]:
    """Report whether ``s`` is one of a map's four fundamental subspaces.

    That is the canonical membership test for the ``Img``/``Ker``/``CoImg``/``CoKer``
    family, and it narrows the type for the caller.
    """
    return isinstance(s, (Img, Ker, CoImg, CoKer))  # audit: ok EX-ISINSTANCE-LADDER — THE canonical FFS membership predicate (definitional 4-member subset) [approved 2026-07-03]


def ffs_defining_map(s: Space) -> object | None:
    """Give the map a fundamental subspace is defined by, or ``None`` for any other space.

    A fundamental subspace carries the map it comes from, which is what makes two
    independently built copies of ``Img(f)`` the same space.
    """
    match s:
        case Img(f, _, _) | Ker(f, _, _) | CoImg(f, _, _) | CoKer(f, _, _):
            return f
        case Scalar() | SVar() | Dual() | OPlus() | OProd() | OPlusRep() | WithInner() | App() | SpaceMeta():
            return None
        case _ as unreachable:
            assert_never(unreachable)


def ffs_kind(s: Space) -> FfsKind | None:
    """Name which of the four fundamental subspaces ``s`` is, or ``None`` for any other space."""
    match s:
        case Img():
            return "img"
        case Ker():
            return "ker"
        case CoImg():
            return "coimg"
        case CoKer():
            return "coker"
        case Scalar() | SVar() | Dual() | OPlus() | OProd() | OPlusRep() | WithInner() | App() | SpaceMeta():
            return None
        case _ as unreachable:
            assert_never(unreachable)


def ffs_superspace(s: Space) -> Space | None:
    """Give the ambient space a fundamental subspace sits inside.

    ``Ker`` and ``CoImg`` live in ``dom f``, ``Img`` and ``CoKer`` in ``cod f``. The ambient
    is taken from the node's declared endpoint when it has one, otherwise from decoding
    ``f``'s map space. The answer is ``None`` for a space that is not a fundamental subspace,
    and for one whose map space cannot be decoded.
    """
    match s:
        case Ker() | CoImg():
            return _ffs_dom(s)
        case Img() | CoKer():
            return _ffs_cod(s)
        case Scalar() | SVar() | Dual() | OPlus() | OProd() | OPlusRep() | WithInner() | App() | SpaceMeta():
            return None
        case _ as unreachable:
            assert_never(unreachable)


def split_map_space(s: Space) -> tuple[Space, Space] | None:
    """Read ``(dom, cod)`` straight off the two-factor map encoding ``OProd(Dual(dom), cod)``.

    Purely syntactic: any other space gives ``None``, and nothing is synthesized. The
    general decoder, which handles more factors and types the map to find them, is
    :func:`grassmann.infer.synth.map_domain_codomain`.
    """
    if isinstance(s, OProd) and len(s.spaces) == 2 and isinstance(s.spaces[0], Dual):  # audit: ok EX-ISINSTANCE-LADDER — canonical syntactic peel: OProd(Dual, ·) or None by contract [approved 2026-07-03]
        return s.spaces[0].space, s.spaces[1]
    return None


